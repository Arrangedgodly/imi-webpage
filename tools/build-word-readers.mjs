// Builds readers-w5.js, readers-w7.js and readers-w9.js from library/word-stories.json (synced by sync-library.mjs).
// Usage: node tools/build-word-readers.mjs
// Each collection has a letter cap (every word is that long or shorter): 5 -> Hibiscus Ribbon (4-5 letter words), 7 -> Lagoon Sprint (6-7), 9 -> Honeycomb Ledger (8-9).
// Tokenised exactly like ops.js tokens(); a story whose longest word does not land in the cap's band is reported and skipped.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(join(root, 'library', 'word-stories.json'), 'utf8'));
const RATE = { 5: 270, 7: 3400, 9: 20000 };            // base rights per word by band (same table as ops.js RATE); ops.js scales it by LIB_PAY at run time
const tokens = t => (t.toLowerCase().match(/[a-z']+/g) || []).map(w => w.replace(/'/g, '')).filter(w => w.length > 1);
const q = a => JSON.stringify(a);

for (const cap of [5, 7, 9]) {
  const books = [], rejected = [];
  for (const e of catalog.filter(e => e.letterCap === cap)) {
    const toks = tokens(e.text), max = Math.max(...toks.map(w => w.length));
    if (max > cap || max < cap - 1) { rejected.push(`${e.slug}: longest word ${max}, cap ${cap}`); continue; }
    books.push({ id: e.slug, title: e.title, text: e.text.replace(/\s+/g, ' ').trim(), total: toks.length, distinct: new Set(toks).size });
  }
  books.sort((a, b) => a.total - b.total || a.distinct - b.distinct || (a.id < b.id ? -1 : 1));       // easiest first
  const out = [`/* ${cap}-letter-cap stories: ${books.length} parodies, generated by tools/build-word-readers.mjs from library/word-stories.json. Do not edit. */`,
    'window.READERS.push(',
    books.map(b => `  { id: ${q(b.id)}, title: ${q(b.title)}, pay: ${b.total * RATE[cap]}, lib: ${cap}, text: ${q(b.text)} }`).join(',\n'),
    ');', ''].join('\n');
  writeFileSync(join(root, `readers-w${cap}.js`), out);
  const t = books.map(b => b.total).sort((a, b) => a - b);
  console.log(`cap ${cap}: ${books.length} books; words min ${t[0]} median ${t[t.length >> 1]} max ${t[t.length - 1]}; ${(out.length / 1024).toFixed(0)} KB`);
  if (rejected.length) console.log(`  REJECTED ${rejected.length}:\n  ` + rejected.join('\n  '));
}
