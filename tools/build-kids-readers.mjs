// Builds readers-kids.js from library/kid-stories (synced by sync-library.mjs).
// Usage: node tools/build-kids-readers.mjs
// Every book must use words of three letters or fewer (tokenised exactly like ops.js tokens()).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'library', 'kid-stories');
const PAY_PER_WORD = 24;                     // task 08 retunes
const tokens = t => (t.toLowerCase().match(/[a-z']+/g) || []).map(w => w.replace(/'/g, '')).filter(w => w.length > 1);

const books = [], rejected = [];
for (const f of readdirSync(dir).filter(f => /^kid-\d+-.*\.md$/.test(f)).sort()) {
  const md = readFileSync(join(dir, f), 'utf8').replace(/\r/g, '');
  const title = (md.match(/^# (.+)$/m) || [])[1];
  const parts = md.split('\n## Story\n');
  if (!title || parts.length !== 2) { rejected.push(`${f}: bad structure`); continue; }
  const text = parts[1].replace(/[*_#>|`]/g, '').replace(/\s+/g, ' ').trim();
  const toks = tokens(text), long = toks.filter(w => w.length > 3);
  if (long.length) { rejected.push(`${f}: long words ${[...new Set(long)].join(',')}`); continue; }
  books.push({ id: 'k-' + f.replace(/^kid-/, '').replace(/\.md$/, ''), title, text, total: toks.length, distinct: new Set(toks).size });
}
books.sort((a, b) => a.total - b.total || a.distinct - b.distinct || (a.id < b.id ? -1 : 1));

const q = a => JSON.stringify(a);
const out = ['/* Kids\' books: 3-letter-or-shorter parodies, generated by tools/build-kids-readers.mjs from library/kid-stories. Do not edit. */',
  'window.READERS.push(',
  books.map(b => `  { id: ${q(b.id)}, title: ${q(b.title)}, pay: ${Math.round(b.total * PAY_PER_WORD)}, kid: true, text: ${q(b.text)} }`).join(',\n'),
  ');', ''].join('\n');
writeFileSync(join(root, 'readers-kids.js'), out);
const t = books.map(b => b.total).sort((a, b) => a - b);
console.log(`${books.length} books written; words min ${t[0]} median ${t[t.length >> 1]} max ${t[t.length - 1]}`);
if (rejected.length) console.log(`REJECTED ${rejected.length}:\n` + rejected.join('\n'));
